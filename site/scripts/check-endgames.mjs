// Offline by default. --refresh queries only the fixed curriculum diagrams/branches, serially.
// API contract: https://github.com/lichess-org/lila-tablebase/blob/main/README.md
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { Chess } from 'chess.js';
import { CURRICULUM } from '../src/curriculum/catalogue.js';
import { compileCurriculum } from '../src/curriculum/curriculum.js';
import { TABLEBASE_SNAPSHOTS } from '../src/curriculum/tablebase-snapshots.js';
import { tablebaseKey, validateTablebaseSnapshot } from '../src/curriculum/tablebase.js';

const target = new URL('../src/curriculum/tablebase-snapshots.js', import.meta.url);
export const digest = result => createHash('sha256').update(JSON.stringify(result)).digest('hex');
/** Save facts only; response SAN/prose is never used as teaching text. */
export function savedResult(raw) {
  const facts = r => ({ category: r.category, dtz: r.dtz, dtm: r.dtm, checkmate: r.checkmate, stalemate: r.stalemate });
  return { ...facts(raw), moves: raw.moves.map(m => ({ uci: m.uci, ...facts(m) })) };
}

/** @param {string[]} args CLI flags. */
export async function checkEndgames(args) {
  if (args.some(a => a !== '--refresh')) throw new Error('Usage: node scripts/check-endgames.mjs [--refresh]');
  let records = TABLEBASE_SNAPSHOTS;
  if (args.includes('--refresh')) {
    const positions = new Set();
    for (const m of CURRICULUM.modules) for (const l of m.lessons) for (const e of l.exercises) if (e.tablebase) {
      const c = new Chess(e.fen);
      for (const u of e.line) {
        positions.add(tablebaseKey(Chess, c.fen()));
        c.move({ from: u.slice(0, 2), to: u.slice(2, 4), promotion: u[4] });
      }
    }
    records = [];
    for (const fen of positions) {
      const url = new URL('https://tablebase.lichess.ovh/standard'); url.searchParams.set('fen', fen);
      const response = await fetch(url, { signal: AbortSignal.timeout(20_000) });
      if (!response.ok) throw new Error(`Tablebase HTTP ${response.status}`);
      const body = await response.text();
      if (body.length > 1_000_000) throw new Error('Tablebase response too large');
      const result = savedResult(JSON.parse(body));
      const record = { fen, url: url.href, retrievedAt: new Date().toISOString(), sha256: digest(result), result };
      records.push(validateTablebaseSnapshot(Chess, record));
      process.stdout.write(`Checked ${records.length}/${positions.size}: ${fen}\n`);
      await new Promise(resolve => setTimeout(resolve, 1000));
    }
  }
  for (const record of records) {
    validateTablebaseSnapshot(Chess, record);
    if (digest(record.result) !== record.sha256) throw new Error('Snapshot digest mismatch');
  }
  const data = compileCurriculum(Chess, CURRICULUM, { tablebases: records });
  const exercises = data.modules.flatMap(m => m.lessons.flatMap(l => l.exercises)).filter(e => e.tablebase);
  if (args.includes('--refresh')) {
    const body = '// Generated by scripts/check-endgames.mjs --refresh; fixed authored positions only.\n'
      + '// Lichess Syzygy API: https://github.com/lichess-org/lila-tablebase/blob/main/README.md\n'
      + '// sha256 covers JSON.stringify(result); categories of moves refer to the child side to move.\n'
      + '/** @type {import(\'./tablebase.js\').TablebaseSnapshot[]} */\nexport const TABLEBASE_SNAPSHOTS = [\n'
      + records.map(r => `  ${JSON.stringify(r)},`).join('\n') + '\n];\n';
    // Validate everything before replacing the checked-in evidence.
    const pending = new URL(target.href + '.tmp');
    try { await fs.writeFile(pending, body); await fs.rename(pending, target); }
    finally { await fs.rm(pending, { force: true }); }
  }
  console.log(`${exercises.length} exercises, ${exercises.reduce((n, e) => n + e.line.length, 0)} plies checked against ${records.length} snapshots (offline unless --refresh).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await checkEndgames(process.argv.slice(2));
