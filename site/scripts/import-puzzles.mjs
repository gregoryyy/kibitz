// Offline Lichess CSV -> bounded browser module. No implicit download or provider use.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { Chess } from 'chess.js';
import { parsePuzzleCsv, PUZZLE_LIMITS } from '../src/curriculum/puzzles.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const hash = value => createHash('sha256').update(value).digest('hex');

/** Validate provenance and produce the exact generated source, without writing or fetching. */
export function compilePuzzleData(/** @type {string} */ csv, manifest) {
  if (manifest?.version !== 1 || manifest.licence !== 'CC0-1.0'
    || manifest.url !== 'https://database.lichess.org/lichess_db_puzzle.csv.zst'
    || !Number.isFinite(Date.parse(manifest.retrievedAt)) || !/^\d{4}-\d\d-\d\dT/.test(manifest.retrievedAt)
    || typeof manifest.selection !== 'string' || !manifest.selection.trim() || manifest.selection.length > 500
    || manifest.sha256 !== hash(csv)) throw new Error('Invalid puzzle manifest or CSV digest');
  const puzzles = parsePuzzleCsv(Chess, csv);
  if (manifest.rows !== puzzles.length) throw new Error('Puzzle manifest row count mismatch');
  const source = { version: 1, licence: manifest.licence, url: manifest.url, retrievedAt: manifest.retrievedAt, selection: manifest.selection, sha256: manifest.sha256, rows: puzzles.length };
  const output = '// Generated by scripts/import-puzzles.mjs from the recorded CC0 Lichess CSV.\n'
    + '// Source format and licence: https://database.lichess.org/#puzzles\n'
    + `export const PUZZLE_SOURCE = ${JSON.stringify(source)};\n`
    + '/** @type {import(\'./puzzles.js\').Puzzle[]} */\nexport const PUZZLES = [\n'
    + puzzles.map(p => `  ${JSON.stringify(p)},`).join('\n') + '\n];\n';
  return { output, puzzles };
}

/**
 * Default inputs are the checked-in starter sample; --check makes no writes. A larger local
 * subset needs its own provenance manifest and stays within the same explicit size bounds.
 * @param {string[]} args
 */
export async function importPuzzles(args) {
  const options = { input: 'data/puzzles/lichess-starter.csv', manifest: 'data/puzzles/lichess-starter.json', output: 'src/curriculum/puzzle-data.js', check: false };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check') options.check = true;
    else if (['--input', '--manifest', '--output'].includes(args[i]) && args[i + 1] && !args[i + 1].startsWith('--')) options[args[i].slice(2)] = args[++i];
    else throw new Error('Usage: import-puzzles.mjs [--check] [--input CSV --manifest JSON --output JS]');
  }
  const input = path.resolve(root, options.input), metadata = path.resolve(root, options.manifest), output = path.resolve(root, options.output);
  if ((await fs.stat(input)).size > PUZZLE_LIMITS.bytes || (await fs.stat(metadata)).size > 4096) throw new Error('Puzzle input too large');
  const { output: body, puzzles } = compilePuzzleData(await fs.readFile(input, 'utf8'), JSON.parse(await fs.readFile(metadata, 'utf8')));
  if (options.check) {
    if (await fs.readFile(output, 'utf8') !== body) throw new Error('Generated puzzle data is stale; run scripts/import-puzzles.mjs');
  } else {
    const pending = output + '.tmp';
    try { await fs.writeFile(pending, body); await fs.rename(pending, output); }
    finally { await fs.rm(pending, { force: true }); }
  }
  console.log(`${puzzles.length} puzzles ${options.check ? 'verified' : 'generated'} offline.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await importPuzzles(process.argv.slice(2));
